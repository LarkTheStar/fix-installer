# Retrieves the published CB Servers launcher (cb-launcher.exe and its data/ runtime,
# GPL-3.0, github.com/CBServers/cb-launcher) from CB's public updater repository and
# writes an inventory of every file: path, size, published SHA-1, computed SHA-1 and
# SHA-256, file version and the time it was retrieved.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\tools\Get-CbLauncherInventory.ps1
#
# The files go to %TEMP%\codhq-cb-inventory\cb-launcher, outside the repository; only
# the inventory (docs/cb-launcher/inventory.json and inventory.md) is written here.
# The launcher manifest also lists CB's game-content manifests (manifest/*.json).
# Those are recorded by name, size and published hash only and are never fetched.

param(
    [string]$Destination = (Join-Path ([IO.Path]::GetTempPath()) 'codhq-cb-inventory\cb-launcher'),
    [string]$DocsFolder = (Join-Path $PSScriptRoot '..\docs\cb-launcher')
)

$ErrorActionPreference = 'Stop'
try { [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12 } catch { Write-Verbose 'Default TLS settings kept.' }
$headers = @{ 'User-Agent' = 'codhq-cb-inventory' }
$manifestUrl = 'https://raw.githubusercontent.com/CBServers/updater/main/updater/cb-launcher.json'
$fileBase = 'https://github.com/CBServers/updater/raw/main/updater/cb-launcher/'

function Get-HashHex { param([string]$Path, [string]$Algorithm) (Get-FileHash -LiteralPath $Path -Algorithm $Algorithm).Hash.ToUpperInvariant() }

$raw = Invoke-RestMethod -Uri $manifestUrl -Headers $headers
$entries = @($raw | Where-Object { $_ -is [array] })
$manifestHash = [string](@($raw | Where-Object { $_ -isnot [array] }) | Select-Object -First 1).ManifestHash
$null = New-Item -ItemType Directory -Path $Destination -Force
$rows = [System.Collections.Generic.List[object]]::new()
$index = 0
foreach ($entry in $entries) {
    $index++
    $path = [string]$entry[0]; $size = [int64]$entry[1]; $sha1 = ([string]$entry[2]).ToUpperInvariant()
    $row = [ordered]@{ Path = $path; Size = $size; PublishedSha1 = $sha1; Sha1 = ''; Sha256 = ''; FileVersion = ''; ProductName = ''; Retrieved = ''; Status = '' }
    if ($path -like 'manifest/*') {
        $row.Status = 'not fetched (CB game-content manifest)'
        $rows.Add([pscustomobject]$row); continue
    }
    $local = Join-Path $Destination ($path -replace '/', '\')
    $parent = Split-Path -Parent $local
    if (-not (Test-Path -LiteralPath $parent)) { $null = New-Item -ItemType Directory -Path $parent -Force }
    $ok = (Test-Path -LiteralPath $local -PathType Leaf) -and (Get-Item -LiteralPath $local).Length -eq $size -and (Get-HashHex $local 'SHA1') -eq $sha1
    if (-not $ok) {
        Write-Output ("[{0}/{1}] {2}" -f $index, $entries.Count, $path)
        Invoke-WebRequest -UseBasicParsing -Uri ($fileBase + ((($path -split '/') | ForEach-Object { [Uri]::EscapeDataString($_) }) -join '/')) -OutFile $local -Headers $headers
    }
    $row.Sha1 = Get-HashHex $local 'SHA1'
    $row.Sha256 = Get-HashHex $local 'SHA256'
    $row.Retrieved = (Get-Item -LiteralPath $local).LastWriteTimeUtc.ToString('o')
    if ($path -match '\.(exe|dll)$') {
        $info = [Diagnostics.FileVersionInfo]::GetVersionInfo($local)
        $row.FileVersion = [string]$info.FileVersion; $row.ProductName = [string]$info.ProductName
    }
    $row.Status = if ((Get-Item -LiteralPath $local).Length -eq $size -and $row.Sha1 -eq $sha1) { 'verified' } else { 'MISMATCH' }
    $rows.Add([pscustomobject]$row)
}

$null = New-Item -ItemType Directory -Path $DocsFolder -Force
$result = [pscustomobject]@{ Generated = [DateTime]::UtcNow.ToString('o'); Manifest = $manifestUrl; ManifestHash = $manifestHash; Files = $rows.ToArray() }
$result | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $DocsFolder 'inventory.json') -Encoding UTF8

$verified = @($rows | Where-Object Status -eq 'verified').Count
$notFetched = @($rows | Where-Object Status -like 'not fetched*').Count
$mismatch = @($rows | Where-Object Status -eq 'MISMATCH').Count
$md = [System.Collections.Generic.List[string]]::new()
$md.Add('# CB launcher inventory')
$md.Add('')
$md.Add("Generated by ``tools/Get-CbLauncherInventory.ps1`` on $([DateTime]::UtcNow.ToString('yyyy-MM-dd HH:mm')) UTC from ``$manifestUrl`` (ManifestHash ``$manifestHash``).")
$md.Add('')
$md.Add("$($rows.Count) entries: $verified retrieved and verified against the published SHA-1, $notFetched game-content manifests listed but not fetched, $mismatch mismatches. Machine-readable copy: ``inventory.json``.")
$md.Add('')
$md.Add('| Path | Size | Published SHA-1 | SHA-256 | Version | Status |')
$md.Add('| --- | ---: | --- | --- | --- | --- |')
foreach ($row in $rows) {
    $md.Add([string]::Format([Globalization.CultureInfo]::InvariantCulture, '| `{0}` | {1:N0} | `{2}` | {3} | {4} | {5} |', $row.Path, $row.Size, $row.PublishedSha1, $(if ($row.Sha256) { '`' + $row.Sha256.Substring(0, 16) + '...`' } else { '' }), $row.FileVersion, $row.Status))
}
$md | Set-Content -LiteralPath (Join-Path $DocsFolder 'inventory.md') -Encoding UTF8
Write-Output "Inventory: $verified verified, $notFetched not fetched, $mismatch mismatches."
